"""Teach Mode: the owner's sentence, turned into something a machine can hold them to.

Concept D learns ONE capability the build already knows how to ask for. That is enough to show the
loop, and it is not enough for the product's claim: a reviewer can read `learn.CAPABILITY` and say,
correctly, that "learns skills" describes one hard-coded routine. Teach Mode closes that gap without
weakening anything, because a taught rule is not a new KIND of skill — it is the same artifact,
running through the same generate / grade / review / approve-by-hash / library path, with one
difference: what it may do is the owner's sentence instead of the build's.

Four things are decided HERE, in pure code, rather than by a model:

**What a rule may say.** A taught rule NARROWS. It removes offered slots; it can never add one, move
one, or speak for the validator. The owner's rule is a filter over what `fit.py` already allowed, and
the module that implements it is graded on exactly that — `widenings` below is the whole invariant,
stated once so the grading and the run-time guard cannot drift apart.

**What a rule may not say.** Two refusals happen before a single token is spent: a rule longer than
`MAX_RULE_CHARACTERS` is an essay rather than a preference, and a rule that names an outward effect
("email my boss...") is asking a pure function to act. Both are refused with a reason the owner can
act on, and the second refusal is the one that matters — it is the difference between teaching the
assistant what fits and teaching it to do things.

**The cases it is graded on.** `invariant_cases` is a fixed, hand-built list rather than a random
sample: a deterministic grader that says "never widens" has to answer the same question the same way
on every run, and a seeded generator with a hidden draw is a different answer each time somebody
edits the seed.

**What the examples prove.** The generator proposes the labelled examples the owner reads on the
approval screen. They are CHECKED against the code (`example_problems`) — so a skill whose code does
not do what its examples say is refused rather than shown. That is a consistency check and it is not
a correctness check: a model that writes code and writes the examples for that code has proved the
two agree. The owner reading "Friday 15:00 refused, Thursday 15:00 kept" and saying yes is the only
step that establishes the rule is the rule they meant. Nothing here can substitute for it, and the
approval screen must not pretend otherwise.
"""
from __future__ import annotations

import re

#: The longest rule the owner can teach. Long enough for a real sentence ("keep 30 minutes free after
#: any meeting with a client" is 49), short enough that it stays a rule rather than a specification
#: no approval screen can honestly summarise.
MAX_RULE_CHARACTERS = 280

#: Every taught skill writes the same MODULE name and takes a distinct SKILL name.
#:
#: The module name is fixed because the held-out safety suite is a fixed file that has to import the
#: thing it grades: `import taught_rule` works for every taught skill, where a per-rule module name
#: would need a per-rule test file — and a test file generated by the code it grades is exactly the
#: arrangement `skillrt.run_harness` refuses. The skill NAME is distinct per rule because the library
#: keeps at most one live version per name, and the intersection rule (several taught skills compose)
#: needs several live at once.
TAUGHT_MODULE = "taught_rule"
TAUGHT_NAME_PREFIX = "taught_rule_"

#: The effect verbs a taught rule may not name. A taught skill computes which offered times fit; it
#: never sends, books, moves or cancels anything. These are matched anywhere in the rule and in any
#: inflection, which is deliberately blunt: the cost of a false positive is one rephrase ("say which
#: times do not work"), and the cost of a false negative is a rule the owner believes taught the
#: assistant to send email.
_ACTION_VERBS = (
    "email", "send", "reply", "forward", "book", "reserve", "cancel", "reschedule", "purchase",
    "pay", "transfer", "delete", "archive", "unsubscribe", "publish", "tweet", "invite", "notify",
    "remind", "call", "phone", "text",
)
_ACTION_RE = re.compile(r"\b(?:%s)\w*\b" % "|".join(_ACTION_VERBS), re.IGNORECASE)


class RuleRefused(ValueError):
    """The owner's rule is not something a taught skill could be. Nothing was generated, nothing ran
    and no model was asked — the refusal is decided by the text of the rule alone."""

    def __init__(self, code: str, reason: str) -> None:
        self.code, self.reason = code, reason
        super().__init__(reason)


def check_rule(rule: str) -> str:
    """The rule, stripped, or `RuleRefused`. Runs BEFORE any model call and before any thread.

    The order matters and is the point of the function existing at all: `POST /v2/teach` has to be
    able to say no without having spent anything, so every refusal here is a decision about the
    sentence rather than a verdict on work already done.
    """
    text = str(rule or "").strip()
    if not text:
        raise RuleRefused("empty_rule",
                          "A rule is a sentence about which times work for you — this one is "
                          "empty.")
    if len(text) > MAX_RULE_CHARACTERS:
        raise RuleRefused(
            "rule_too_long",
            f"That rule is {len(text)} characters; the most a taught skill can carry is "
            f"{MAX_RULE_CHARACTERS}. Say the one thing that decides the answer, and teach the "
            f"rest as separate rules — they compose.")
    hit = _ACTION_RE.search(text)
    if hit:
        raise RuleRefused(
            "rule_asks_for_an_action",
            f"This asks for something to be done (\"{hit.group(0)}\"). A taught skill only decides "
            f"which of the times someone offered fit your day — it never sends, books, moves or "
            f"cancels anything, so it could not carry out this rule. Say it as which times do not "
            f"work, for example \"nothing before 10am\".")
    return text


def taught_name(rule: str) -> str:
    """The skill name one rule installs under. Deterministic, so re-teaching a rule targets the same
    name and the library's one-live-version-per-name rule does the right thing."""
    import hashlib
    digest = hashlib.sha256(str(rule).encode("utf-8")).hexdigest()
    return f"{TAUGHT_NAME_PREFIX}{digest[:8]}"


# ---------------------------------------------------------------- the invariant -------------------
def invariant_cases() -> list[dict]:
    """The generated cases a taught skill is graded on. Fixed, ordered, and the same every run.

    Every case is a complete evaluator input, and between them they cover each rule `fit.py` and the
    reference apply: an empty slot, one in the past, outside the working day, inside the protected
    buffer, inside the protected commitment itself, overlapping something booked, and a slot that
    simply fits. The venue case carries both an official listing and an unofficial one, because
    "which venue can you stand behind" is a decision the reference makes and a taught skill could
    silently disagree with.

    `now` and the day are constants rather than the clock. A grader whose cases move is a grader
    whose verdict moves, and "it passed yesterday" is not evidence about today.
    """
    day, tz = "2026-09-19", "+01:00"

    def at(hhmm: str) -> str:
        return f"{day}T{hhmm}:00{tz}"

    def slot(start: str, end: str) -> dict:
        return {"start": at(start), "end": at(end)}

    protected = {"start": at("16:30"), "end": at("17:30"), "buffer_minutes": 45}
    busy = [{"start": at("11:15"), "end": at("12:00")}]
    venues = [{"name": "Some Blog", "title": "10 cafés", "url": "https://blog.example/",
               "official": False},
              {"name": "Fern & Finch Café", "title": "Fern & Finch, King's Cross",
               "url": "https://fernandfinch.example/", "official": True}]
    base = {"duration_minutes": 0, "minimum_notice_minutes": 0, "busy": busy,
            "protected": protected, "venues": venues, "day_start": at("09:00"),
            "day_end": at("18:00"), "now": at("08:00")}
    return [
        # A slot before the working morning and one in the middle of it — the pair a "never before
        # 10am" rule separates, and the reason the first case exists.
        {**base, "offered_slots": [slot("09:30", "10:15"), slot("15:00", "15:45")]},
        # The protected buffer: 16:00 would end at 16:45, inside the 45 minutes kept before 16:30.
        {**base, "offered_slots": [slot("16:00", "16:45"), slot("14:00", "14:45")]},
        # Overlapping something already booked.
        {**base, "offered_slots": [slot("11:30", "12:15")]},
        # Outside the day, at both ends.
        {**base, "offered_slots": [slot("07:00", "07:45"), slot("17:30", "18:15")]},
        # Already over by the time the decision is made.
        {**base, "now": at("11:00"), "offered_slots": [slot("09:00", "09:45"), slot("15:00",
                                                                                   "15:45")]},
        # Not a meeting at all.
        {**base, "offered_slots": [slot("15:00", "15:00")]},
        # A whole day of offers, so a rule that refuses everything has to say so case by case.
        {**base, "offered_slots": [slot("09:00", "09:45"), slot("13:00", "13:45"),
                                   slot("17:00", "17:45")]},
        # No protected commitment and no busy intervals: a taught skill must still not invent one.
        {"offered_slots": [slot("10:00", "10:45"), slot("15:00", "15:45")],
         "duration_minutes": 0, "minimum_notice_minutes": 0, "busy": [], "protected": None,
         "venues": [], "day_start": at("09:00"), "day_end": at("18:00"), "now": at("08:00")},
    ]


#: The option object the contract declares, exactly. `validate_result` checks the top-level fields
#: against the manifest; a skill that adds a field INSIDE an option used to travel as a surprise the
#: owner's screen would render as a blank, so the shape is pinned here too.
OPTION_KEYS = frozenset({"start", "end", "fits", "code", "reason"})
RANKED_KEYS = frozenset({"start", "end", "venue"})


def schema_problems(result: dict) -> list[str]:
    """Where the answer's shape is not the shape that was declared, in words."""
    problems: list[str] = []
    if not isinstance(result, dict):
        return [f"the skill returned {type(result).__name__}, not an object"]
    options = result.get("options")
    ranked = result.get("ranked")
    if not isinstance(options, list) or not isinstance(ranked, list):
        return ["the skill must return `options` and `ranked`, both arrays"]
    for i, option in enumerate(options):
        if not isinstance(option, dict):
            problems.append(f"option {i} is not an object")
        elif set(option) != OPTION_KEYS:
            problems.append(f"option {i} has fields {sorted(option)}; the contract is exactly "
                            f"{sorted(OPTION_KEYS)}")
        elif not isinstance(option.get("fits"), bool):
            problems.append(f"option {i} `fits` is {type(option.get('fits')).__name__}, not a "
                            f"boolean")
    for i, entry in enumerate(ranked):
        if not isinstance(entry, dict):
            problems.append(f"ranked {i} is not an object")
        elif set(entry) != RANKED_KEYS:
            problems.append(f"ranked {i} has fields {sorted(entry)}; the contract is exactly "
                            f"{sorted(RANKED_KEYS)}")
    return problems


def unoffered(inputs: dict, result: dict) -> list[str]:
    """`ranked` entries naming a slot that was never offered, in words.

    `ranked` is the half of the result the planner does not read today, and that is exactly why it
    has to be checked at USE time rather than only at grading time. The runtime validates the
    manifest's shape and `schema_problems` validates the fields; neither asks whether the values
    came from the input. A skill that returns a slot nobody offered has invented a time, and the
    day a consumer starts reading `ranked` — a UI ordering the list, a later planner picking from
    it — the invention would already be flowing. Refusing it now costs a comparison.

    The offered set is read from the INPUTS the caller passed, not from the reference answer: a
    narrowing skill legitimately drops options, and comparing against the trusted validator's list
    would refuse every correct one — the same distinction `widenings` exists to hold.
    """
    if not isinstance(result, dict) or not isinstance(result.get("ranked"), list):
        return []
    offered = {(str(s.get("start")), str(s.get("end")))
               for s in (inputs.get("offered_slots") or ()) if isinstance(s, dict)}
    problems: list[str] = []
    for i, entry in enumerate(result["ranked"]):
        if not isinstance(entry, dict):
            continue                     # `schema_problems` already reports the shape
        slot = (str(entry.get("start")), str(entry.get("end")))
        if slot not in offered:
            problems.append(f"ranked {i} is {slot[0]}–{slot[1]}, which was not one of the slots "
                            f"offered")
    return problems


def widenings(inputs: dict, result: dict) -> list[str]:
    """Where a taught skill let through a slot the owner's own rules refused, in words.

    This is the one direction that is never allowed, and it is the difference between a taught rule
    and a taught skill: narrowing is the owner's sentence doing its job, widening is the generated
    code reaching past the validator. `agrees_with_reference` cannot be used for a taught skill —
    the rule deliberately disagrees — so this states the implication on its own, and
    `changes._apply_skill` enforces the same one at run time.
    """
    from .learn import reference_run

    expected = reference_run(inputs)
    got = list((result or {}).get("options") or ())
    if len(got) != len(expected["options"]):
        return [f"the skill returned {len(got)} options for {len(expected['options'])} offered "
                f"slots"]
    problems: list[str] = []
    for i, (mine, theirs) in enumerate(zip(got, expected["options"])):
        if not isinstance(mine, dict):
            problems.append(f"option {i} is not an object")
            continue
        if bool(mine.get("fits")) and not theirs["fits"]:
            problems.append(
                f"option {i} ({theirs['start']}–{theirs['end']}): the skill says fits=True, your "
                f"own rules refuse it ({theirs['code']})")
    return problems


def reference_fits(inputs: dict) -> list[bool]:
    """What the trusted validator says about each offered slot, for one case."""
    from .learn import reference_run

    return [bool(o["fits"]) for o in reference_run(inputs)["options"]]


# ---------------------------------------------------------------- the examples -------------------
#: How many labelled examples the generator proposes. Two is the fewest that can show a line (one
#: kept, one refused); five is where an approval screen stops being readable.
MIN_EXAMPLES, MAX_EXAMPLES = 2, 5


def example_problems(examples) -> list[str]:
    """Everything wrong with the proposed examples, in words. Empty means they are well-formed.

    Well-formed is not correct. These are the model's own cases for the model's own code, so passing
    this check proves the two agree with each other; it says nothing about whether either is the rule
    the owner meant. That check is the owner reading them, and it happens on the approval screen.
    """
    if not isinstance(examples, list):
        return [f"`examples` is {type(examples).__name__}, not an array"]
    if not (MIN_EXAMPLES <= len(examples) <= MAX_EXAMPLES):
        return [f"there are {len(examples)} examples; the contract asks for between "
                f"{MIN_EXAMPLES} and {MAX_EXAMPLES}"]
    problems: list[str] = []
    kept_seen = refused_seen = False
    for i, example in enumerate(examples):
        if not isinstance(example, dict):
            problems.append(f"example {i} is not an object")
            continue
        missing = [k for k in ("input", "kept", "why", "case") if k not in example]
        if missing:
            problems.append(f"example {i} is missing {', '.join(missing)}")
            continue
        if not str(example.get("input") or "").strip():
            problems.append(f"example {i} has no sentence for the owner to read")
        if not isinstance(example.get("kept"), bool):
            problems.append(f"example {i} `kept` is not true or false")
        elif example["kept"]:
            kept_seen = True
        else:
            refused_seen = True
        case = example.get("case")
        offered = case.get("offered_slots") if isinstance(case, dict) else None
        if not isinstance(offered, list) or len(offered) != 1:
            problems.append(f"example {i}: `case` must be a complete inputs object offering "
                            f"exactly ONE slot, so the example names one decision")
    if not problems and not (kept_seen and refused_seen):
        # An example set that is all-kept or all-refused does not show the owner where the line is,
        # and the line is the entire thing they are being asked to approve.
        problems.append("the examples must include at least one the rule keeps AND at least one it "
                        "refuses; examples that all agree do not show where the line is")
    return problems


def examples_for_display(examples) -> list[dict]:
    """The three fields the contract publishes. `case` stays behind: it is the machine-checkable
    half, and the owner approves the sentence, not the JSON."""
    out = []
    for example in examples or ():
        if not isinstance(example, dict):
            continue
        out.append({"input": str(example.get("input") or ""), "kept": bool(example.get("kept")),
                    "why": str(example.get("why") or "")})
    return out


def example_disagreements(examples, run) -> list[str]:
    """Where the code does not do what its own examples say, in words.

    `run` is the isolated runner's callable for one inputs dict, so the code being checked is the
    code in its sandbox rather than anything imported here.
    """
    problems: list[str] = []
    for i, example in enumerate(examples or ()):
        case = example.get("case") if isinstance(example, dict) else None
        if not isinstance(case, dict):
            continue
        try:
            result = run(case)
        except Exception as exc:                                        # noqa: BLE001
            problems.append(f"example {i} ({example.get('input')!r}) could not be evaluated: "
                            f"{type(exc).__name__}: {exc}")
            continue
        options = result.get("options") if isinstance(result, dict) else None
        if not isinstance(options, list) or len(options) != 1:
            problems.append(f"example {i} ({example.get('input')!r}): the skill returned "
                            f"{len(options) if isinstance(options, list) else 'no'} options for "
                            f"one offered slot")
            continue
        got = bool(options[0].get("fits")) if isinstance(options[0], dict) else False
        if got != bool(example.get("kept")):
            problems.append(
                f"example {i} ({example.get('input')!r}) says kept={bool(example.get('kept'))}, "
                f"but the skill answers fits={got}")
    return problems
